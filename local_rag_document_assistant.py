"""## 5. Build the RAG pipeline

What happens:
1. Extract text from the uploaded PDF.
2. Split it into overlapping chunks.
3. Convert chunks into embedding vectors.
4. Store the vectors and text in ChromaDB.
5. Retrieve the most relevant chunks for each question.
6. Send only those retrieved passages to Qwen through Ollama.
"""

import os, re, uuid, requests, chromadb, torch
from pypdf import PdfReader
from sentence_transformers import SentenceTransformer
from concurrent.futures import ThreadPoolExecutor

OLLAMA_URL = "http://127.0.0.1:11434/api/chat"
LLM_MODEL = "qwen2.5:1.5b"
EMBED_MODEL_NAME = "sentence-transformers/all-MiniLM-L6-v2"

# Use the Colab GPU for embeddings when available
embedding_device = "cuda" if torch.cuda.is_available() else "cpu"
print("Embedding device:", embedding_device)

embedding_model = SentenceTransformer(EMBED_MODEL_NAME, device=embedding_device)

# Persistent database survives app interactions during this runtime
client = chromadb.PersistentClient(path="/content/rag_chroma_db")
collection_name = "document_chunks"

# Start with a clean collection for this notebook session
try:
    client.delete_collection(collection_name)
except Exception:
    pass
collection = client.create_collection(
    name=collection_name,
    metadata={"hnsw:space": "cosine"}
)

def extract_pdf_text(pdf_path):
    try:
        reader = PdfReader(pdf_path)
    except Exception as e:
        raise ValueError(f"Failed to parse PDF file: {str(e)}")

    pages = []
    for page_num, page in enumerate(reader.pages, start=1):
        text = page.extract_text() or ""
        text_cleaned = re.sub(r'\s+', ' ', text).strip()
        if text_cleaned:
            pages.append((page_num, text_cleaned))
    return pages

def split_into_chunks(text, chunk_size=900, overlap=150):
    words = text.split()
    chunks = []
    start = 0
    while start < len(words):
        end = min(start + chunk_size, len(words))
        chunk = " ".join(words[start:end]).strip()
        if chunk:
            chunks.append(chunk)
        if end == len(words):
            break
        start = end - overlap
    return chunks

def ingest_pdf(pdf_path):
    pages = extract_pdf_text(pdf_path)
    if not pages:
        raise ValueError("No selectable text found. This may be a scanned or image-only PDF.")

    ids, documents, metadatas = [], [], []

    # Efficient concurrent preparation
    def process_single_page(page_data):
        page_num, page_text = page_data
        page_chunks = split_into_chunks(page_text)
        return page_num, page_chunks

    with ThreadPoolExecutor() as executor:
        results = list(executor.map(process_single_page, pages))

    for page_num, page_chunks in results:
        for chunk_index, chunk in enumerate(page_chunks):
            ids.append(str(uuid.uuid4()))
            documents.append(chunk)
            metadatas.append({"page": int(page_num), "chunk": int(chunk_index)})

    if not documents:
        raise ValueError("The PDF did not contain enough text to create chunks.")

    # Generate embeddings in optimal batch size
    embeddings = embedding_model.encode(
        documents,
        batch_size=64,
        normalize_embeddings=True,
        show_progress_bar=False
    ).tolist()

    # Efficiently wipe previous index without re-allocating client resource
    existing = collection.get()
    if existing and existing.get("ids"):
        collection.delete(ids=existing["ids"])

    collection.add(
        ids=ids,
        documents=documents,
        metadatas=metadatas,
        embeddings=embeddings
    )
    return len(pages), len(documents)

def retrieve_context(question, top_k=4):
    if collection.count() == 0:
        raise ValueError("Please upload and index a PDF document first.")
    query_embedding = embedding_model.encode(
        [question], normalize_embeddings=True
    ).tolist()
    results = collection.query(
        query_embeddings=query_embedding,
        n_results=min(top_k, collection.count()),
        include=["documents", "metadatas", "distances"]
    )

    passages = []
    for doc, meta, distance in zip(
        results["documents"][0],
        results["metadatas"][0],
        results["distances"][0]
    ):
        passages.append({
            "text": doc,
            "page": meta["page"],
            "distance": distance
        })
    return passages

def ask_rag(question):
    if not question or not question.strip():
        return "Please enter a valid question.", ""

    passages = retrieve_context(question)
    context = "\n\n".join(
        f"[Source: page {p['page']}]\n{p['text']}" for p in passages
    )

    system_prompt = (
        "You are a careful document question-answering assistant. "
        "Answer using only the supplied context. If the answer is not in the context, "
        "say you could not find it in the uploaded document. Do not invent facts. "
        "Cite page numbers when making claims."
    )
    user_prompt = f"DOCUMENT CONTEXT:\n{context}\n\nQUESTION: {question}"

    response = requests.post(
        OLLAMA_URL,
        json={
            "model": LLM_MODEL,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "stream": False,
            "options": {"temperature": 0.15}
        },
        timeout=180
    )
    response.raise_for_status()
    answer = response.json()["message"]["content"]

    source_lines = []
    for i, p in enumerate(passages, start=1):
        source_lines.append(
            f"{i}. Page {p['page']} (retrieval distance: {p['distance']:.3f})"
        )
    return answer, "\n".join(source_lines)

print("Upgraded parallel RAG pipeline is ready.")

"""## 6. Create the document-chat interface

Upload a PDF, click **Index PDF**, then ask questions. The answer and retrieved source pages appear below.
"""

import gradio as gr

def index_uploaded_file(file_path):
    if file_path is None:
        return "Please upload a PDF first."
    try:
        page_count, chunk_count = ingest_pdf(file_path)
        return f"Indexed successfully: {page_count} pages converted into {chunk_count} searchable chunks."
    except Exception as e:
        return f"Indexing failed: {type(e).__name__}: {e}"

def answer_in_ui(question):
    try:
        answer, sources = ask_rag(question)
        return answer, sources
    except Exception as e:
        return f"Error: {type(e).__name__}: {e}", ""

with gr.Blocks(title="Local AI Document Assistant") as demo:
    gr.Markdown(
        "# 📚 Local AI Document Assistant\n"
        "Upload a PDF and ask questions. Answers are generated by Qwen through Ollama "
        "using relevant passages retrieved from your document."
    )
    with gr.Row():
        pdf_file = gr.File(label="Upload a PDF", file_types=[".pdf"], type="filepath")
    index_button = gr.Button("Index PDF", variant="primary")
    index_status = gr.Textbox(label="Indexing status", interactive=False)
    index_button.click(index_uploaded_file, inputs=pdf_file, outputs=index_status)

    question = gr.Textbox(
        label="Ask a question",
        placeholder="Example: Explain the main concept discussed in this document..."
    )
    ask_button = gr.Button("Ask", variant="primary")
    answer = gr.Markdown(label="Answer")
    sources = gr.Textbox(label="Retrieved source pages", lines=5, interactive=False)
    ask_button.click(answer_in_ui, inputs=question, outputs=[answer, sources])
    question.submit(answer_in_ui, inputs=question, outputs=[answer, sources])

    gr.Markdown(
        "**Note:** This is a prototype. Scanned PDFs need OCR, and answers depend on "
        "the quality of the extracted text and retrieved passages."
    )

demo.launch(share=True, debug=True)